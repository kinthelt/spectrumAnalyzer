#!/usr/bin/env python3
"""Builds the web page into the firmware.

    python3 tools/embed_web.py           regenerate firmware/.../src/web/WebPage.h
    python3 tools/embed_web.py --check   fail if WebPage.h is out of date (run by make -C test)

Takes web/index.html, puts web/vendor/qrcode.js inside it (the lights serve one
file, so a phone needs one request), gzips it, and writes the bytes as a C++ array.
Run it after every change to web/ and commit the regenerated WebPage.h with it:
the Arduino IDE can't run this script, so the header is what it builds from.
"""
import argparse
import gzip
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
HEADER = ROOT / "firmware/SpectrumAnalyzer/src/web/WebPage.h"
SCRIPT_TAG = '<script src="vendor/qrcode.js"></script>'


def build_page():
    """The page exactly as the lights serve it (before compression), as bytes."""
    html = (WEB / "index.html").read_text(encoding="utf-8")
    lib = (WEB / "vendor/qrcode.js").read_text(encoding="utf-8")
    if html.count(SCRIPT_TAG) != 1:
        sys.exit(f"embed_web: expected exactly one {SCRIPT_TAG} in web/index.html")
    if "</script" in lib.lower():
        sys.exit("embed_web: qrcode.js contains '</script', which would end the inline script early")
    return html.replace(SCRIPT_TAG, "<script>\n" + lib + "\n</script>").encode("utf-8")


def build_header():
    page = build_page()
    # mtime=0 and no file name: the same page always gives the same bytes, so the
    # header only changes when the page does.
    packed = gzip.compress(page, compresslevel=9, mtime=0)
    digest = hashlib.sha256(page).hexdigest()[:16]
    rows = []
    for i in range(0, len(packed), 20):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in packed[i:i + 20]) + ",")
    return (
        "// GENERATED by tools/embed_web.py from web/index.html and web/vendor/qrcode.js.\n"
        "// Do not edit: change the files in web/ and run  python3 tools/embed_web.py\n"
        f"// Page: {len(page)} bytes, gzipped: {len(packed)} bytes, sha256 {digest}\n"
        "#pragma once\n\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "namespace web_page {\n\n"
        f'constexpr const char* kEtag = "\\"{digest}\\"";\n'
        f"constexpr size_t kGzipSize = {len(packed)};\n"
        "constexpr uint8_t kGzip[kGzipSize] = {\n" + "\n".join(rows) + "\n};\n\n"
        "}  // namespace web_page\n"
    ), len(page), len(packed)


def main():
    parser = argparse.ArgumentParser(description="Build web/index.html into the firmware.")
    parser.add_argument("--check", action="store_true", help="only check WebPage.h is up to date")
    args = parser.parse_args()
    text, raw, packed = build_header()
    current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
    if args.check:
        if current != text:
            sys.exit("WebPage.h is out of date: run  python3 tools/embed_web.py  and commit it")
        print(f"WebPage.h is up to date ({raw} bytes, {packed} gzipped)")
        return
    if current == text:
        print(f"WebPage.h already up to date ({raw} bytes, {packed} gzipped)")
    else:
        HEADER.write_text(text, encoding="utf-8")
        print(f"wrote {HEADER.relative_to(ROOT)} ({raw} bytes, {packed} gzipped)")


if __name__ == "__main__":
    main()
